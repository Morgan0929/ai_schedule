def run():
    passed = 0
    failed = 0
    for text, exp_type, exp_start, exp_end in CASES:
        r = resolve_time_range(text, TODAY)
        ok_type = r["type"] == exp_type

        tr = r.get("time_range") or {}
        got_start = tr.get("start") if tr else None
        got_end = tr.get("end") if tr else None
        ok_start = got_start == exp_start
        ok_end = got_end == exp_end

        ok = ok_type and ok_start and ok_end
        if ok:
            passed += 1
        else:
            failed += 1
            print(f"FAIL | {text}")
            print(f"       type: got={r['type']} exp={exp_type}")
            print(f"       start: got={got_start} exp={exp_start}")
            print(f"       end:   got={got_end} exp={exp_end}")

    print(f"\n{'='*50}")
    print(f"Results: {passed}/{len(CASES)} passed")
    if failed:
        print(f"         {failed} FAILED")
    else:
        print("         100% — ALL PASSED")
    return failed == 0


if __name__ == "__main__":
    ok = run()
    sys.exit(0 if ok else 1)
